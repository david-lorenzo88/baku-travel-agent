#!/usr/bin/env python3
"""Copy the shared catalog and pricing module into each self-contained skill package.

Usage: python tools/sync_shared.py [--check]

  skills-src/_shared/catalog.json -> skills-src/<skill>/references/catalog.json
  skills-src/_shared/pricing.py   -> skills-src/<skill>/scripts/pricing.py  (with a GENERATED header)

--check  exits 1 if any copy is missing or out of date, without writing anything.
Never edit the copies by hand; edit skills-src/_shared/ and re-run this tool.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SHARED = ROOT / "skills-src" / "_shared"
SKILLS = ("baku-trip-catalog", "confirm-trip-plan", "export-trip-plan-pdf")
HEADER = "# GENERATED by tools/sync_shared.py — edit skills-src/_shared/ instead\n"


def expected_files() -> dict[Path, bytes]:
    catalog = (SHARED / "catalog.json").read_bytes()
    pricing = HEADER.encode("utf-8") + (SHARED / "pricing.py").read_bytes()
    out: dict[Path, bytes] = {}
    for skill in SKILLS:
        base = ROOT / "skills-src" / skill
        out[base / "references" / "catalog.json"] = catalog
        out[base / "scripts" / "pricing.py"] = pricing
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv[1:]
    stale = []
    for path, content in expected_files().items():
        current = path.read_bytes() if path.is_file() else None
        if current == content:
            continue
        stale.append(path.relative_to(ROOT))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if check:
        if stale:
            print("out of date: " + ", ".join(map(str, stale)))
            return 1
        print("all shared copies up to date")
        return 0
    print(f"synced {len(stale)} file(s)" if stale else "already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
