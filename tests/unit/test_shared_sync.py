"""T021: every synced copy must match its skills-src/_shared source (ignoring the header line)."""
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
SHARED = ROOT / "skills-src" / "_shared"
SKILLS = ("baku-trip-catalog", "confirm-trip-plan", "export-trip-plan-pdf")
HEADER_PREFIX = "# GENERATED by tools/sync_shared.py"


@pytest.mark.parametrize("skill", SKILLS)
def test_catalog_copy_matches(skill):
    copy = ROOT / "skills-src" / skill / "references" / "catalog.json"
    assert copy.is_file(), f"{copy} missing — run tools/sync_shared.py"
    assert copy.read_bytes() == (SHARED / "catalog.json").read_bytes(), f"{copy} is stale"


@pytest.mark.parametrize("skill", SKILLS)
def test_pricing_copy_matches(skill):
    copy = ROOT / "skills-src" / skill / "scripts" / "pricing.py"
    assert copy.is_file(), f"{copy} missing — run tools/sync_shared.py"
    first, rest = copy.read_text(encoding="utf-8").split("\n", 1)
    assert first.startswith(HEADER_PREFIX)
    assert rest == (SHARED / "pricing.py").read_text(encoding="utf-8"), f"{copy} is stale"
